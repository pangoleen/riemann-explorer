"""Generate Taylor coefficients of the Riemann–Siegel correction terms C0..C4.

Each C_k(p) is written as a polynomial in x = p - 1/2, where p is the
fractional part of sqrt(t / 2π). The output is src/math/rsCoeffs.ts.

Formulas (Edwards, "Riemann's Zeta Function", §7.4), with
Ψ(p) = cos(2π(p² − p − 1/16)) / cos(2πp):

  C0 = Ψ
  C1 = −Ψ⁽³⁾ / (96 π²)
  C2 = Ψ⁽²⁾ / (64 π²) + Ψ⁽⁶⁾ / (18432 π⁴)
  C3 = −Ψ⁽¹⁾ / (64 π²) − Ψ⁽⁵⁾ / (3840 π⁴) − Ψ⁽⁹⁾ / (5308416 π⁶)
  C4 = Ψ / (128 π²) + 19 Ψ⁽⁴⁾ / (24576 π⁴) + 11 Ψ⁽⁸⁾ / (5898240 π⁶)
       + Ψ⁽¹²⁾ / (2038431744 π⁸)

Ψ is entire on the real line (the zeros of the numerator cancel the poles),
so its Taylor series about p = 1/2 converges on [0, 1].
"""

from __future__ import annotations

import json
from pathlib import Path

import mpmath as mp

ROOT = Path(__file__).resolve().parent.parent
N_TERMS = 72  # Taylor terms of Ψ; derivatives up to order 12 keep ≥ 60 terms
KEEP = 44     # terms written out per C_k (|x| ≤ 1/2, tail < 1e-17)


def psi_series(n: int) -> list[mp.mpf]:
    """Taylor coefficients a_j of Ψ(1/2 + x) = Σ a_j x^j, by exact series algebra."""
    # Ψ(1/2+x): p² − p − 1/16 = x² − 5/16 ; cos(2πp) = −cos(2πx)
    # Ψ = −cos(2π(x² − 5/16)) / cos(2πx)
    two_pi = 2 * mp.pi
    # numerator series in x: cos(2πx² − 5π/8)
    c, s = mp.cos(-5 * mp.pi / 8), mp.sin(-5 * mp.pi / 8)
    # cos(a + b) with a = 2πx², b = −5π/8 → cos a cos b − sin a sin b
    num = [mp.mpf(0)] * n
    for k in range(0, n):
        deg = 2 * k
        if deg >= n:
            break
        term = (two_pi ** k) / mp.factorial(k)
        if k % 4 == 0:
            num[deg] += term * c
        elif k % 4 == 1:
            num[deg] += -term * s
        elif k % 4 == 2:
            num[deg] += -term * c
        else:
            num[deg] += term * s
    # denominator: cos(2πx)
    den = [mp.mpf(0)] * n
    for k in range(0, n, 2):
        den[k] = ((-1) ** (k // 2)) * (two_pi ** k) / mp.factorial(k)
    # series division q = num / den
    q = [mp.mpf(0)] * n
    for i in range(n):
        acc = num[i]
        for j in range(1, i + 1):
            acc -= den[j] * q[i - j]
        q[i] = acc / den[0]
    return [-v for v in q]


def deriv(a: list[mp.mpf], m: int) -> list[mp.mpf]:
    """Coefficients of the m-th derivative of Σ a_j x^j."""
    out = []
    for j in range(m, len(a)):
        f = mp.mpf(1)
        for r in range(j - m + 1, j + 1):
            f *= r
        out.append(a[j] * f)
    return out


def comb(*parts: tuple[mp.mpf, list[mp.mpf]]) -> list[mp.mpf]:
    n = min(len(p) for _, p in parts)
    return [sum(w * p[i] for w, p in parts) for i in range(n)]


def main() -> None:
    mp.mp.dps = 60
    a = psi_series(N_TERMS)
    pi = mp.pi
    D = lambda m: deriv(a, m)  # noqa: E731
    C = [
        a,
        comb((-1 / (96 * pi**2), D(3))),
        comb((1 / (64 * pi**2), D(2)), (1 / (18432 * pi**4), D(6))),
        comb((-1 / (64 * pi**2), D(1)), (-1 / (3840 * pi**4), D(5)), (-1 / (5308416 * pi**6), D(9))),
        comb(
            (1 / (128 * pi**2), a),
            (mp.mpf(19) / (24576 * pi**4), D(4)),
            (mp.mpf(11) / (5898240 * pi**6), D(8)),
            (1 / (2038431744 * pi**8), D(12)),
        ),
    ]
    # self-check against direct evaluation of Ψ
    for p in (mp.mpf("0.1"), mp.mpf("0.37"), mp.mpf("0.93")):
        direct = mp.cos(2 * pi * (p * p - p - mp.mpf(1) / 16)) / mp.cos(2 * pi * p)
        series = sum(c * (p - 0.5) ** j for j, c in enumerate(C[0][:KEEP]))
        assert abs(direct - series) < 1e-15, (p, direct, series)
    rows = [[float(v) for v in ck[:KEEP]] for ck in C]
    out = ROOT / "src" / "math" / "rsCoeffs.ts"
    out.write_text(
        "// Generated by pipeline/rs_coeffs.py. Do not edit.\n"
        "// Taylor coefficients of Riemann–Siegel C0..C4 in x = p − 1/2.\n"
        f"export const RS_COEFFS: readonly (readonly number[])[] = {json.dumps(rows)};\n"
    )
    print(f"wrote {out} ({len(rows)} × {KEEP})")


if __name__ == "__main__":
    main()
